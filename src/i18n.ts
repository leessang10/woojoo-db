function readLanguage(): Language {
  try {
    const saved = localStorage.getItem('woojoo-language');
    if (saved === 'ko' || saved === 'en') return saved;
  } catch { /* Preferences are optional in restricted environments. */ }
  return navigator.language.toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

let language = readLanguage();
const listeners = new Set<() => void>();
document.documentElement.lang = language;

export function setLanguage(next: Language) {
  language = next;
  document.documentElement.lang = next;
  try { localStorage.setItem('woojoo-language', next); } catch { /* Session-only preference. */ }
  listeners.forEach(listener => listener());
}

export function t(key: string, values: Record<string, string | number> = {}) {
  const template = messages[`${key}_en`]
    ? messages[language === 'en' ? `${key}_en` : key]
    : language === 'en' ? messages[key] ?? key : key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export function useLanguage() {
  const current = useSyncExternalStore(
    callback => { listeners.add(callback); return () => { listeners.delete(callback); }; },
    () => language,
  );
  return { language: current, setLanguage, t };
}
