import { test, expect } from './fixtures';
test('explore, filter, edit, review, save, export, and run SQL', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByText('Alex Morgan', { exact: true })).toBeVisible();
  await page.getByLabel('결과 필터').fill('sofia');
  await expect(page.getByText('Sofia Chen', { exact: true })).toBeVisible();
  await expect(page.getByText('Alex Morgan', { exact: true })).not.toBeVisible();
  await page.getByLabel('결과 필터').clear();
  await page.getByText('Alex Morgan', { exact: true }).dblclick();
  await page.getByLabel('셀 값').fill('Alex Updated');
  await page.getByRole('button', {name:'변경 대기열에 추가'}).click();
  await expect(page.getByText('Alex Updated', { exact: true })).toBeVisible();
  await page.getByRole('button', {name:/변경 검토/}).click();
  await expect(page.getByRole('heading', {name:'변경 사항 검토'})).toBeVisible();
  await page.getByRole('button', {name:'1개 행 적용'}).click();
  await expect(page.getByRole('heading', {name:'변경 사항 검토'})).not.toBeVisible();
  await expect(page.getByText('Alex Updated', { exact: true })).toBeVisible();
  await page.getByLabel('테이블 새로고침').click();
  await expect(page.getByText('Alex Updated', { exact: true })).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByLabel('CSV 내보내기').click();
  expect((await download).suggestedFilename()).toBe('users-results.csv');
  await page.locator('.run-button').click();
  await expect(page.getByText('쿼리 결과 · 편집 가능')).toBeVisible();
  await page.screenshot({path:'docs/research/dbeaver/woojoo-preview.png', fullPage:true});
  expect(errors).toEqual([]);
});
test('NULL editing is explicit and connection form supports all engines', async ({ page }) => {
  await page.goto('/');
  await page.getByText('Alex Morgan', { exact:true }).dblclick();
  await page.getByLabel('NULL로 설정').check();
  await page.getByRole('button', {name:'변경 대기열에 추가'}).click();
  await expect(page.getByText('NULL', {exact:true})).toBeVisible();
  await page.locator('.result-toolbar').getByRole('button',{name:'취소',exact:true}).click();
  await expect(page.getByText('Alex Morgan',{exact:true})).toBeVisible();
  await page.getByLabel('새 연결').click();
  await page.getByRole('button',{name:'MariaDB',exact:true}).click();
  await expect(page.getByLabel('포트',{exact:true})).toHaveValue('3306');
  await page.getByRole('button',{name:'연결 테스트',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('데스크톱 앱');
});
